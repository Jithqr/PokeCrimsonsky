export const CUSTOM_SPRITE_URL = (clean: string): string | null => {
  const val = CUSTOM_SPRITES[clean];
  if (!val) return null;
  if (val.startsWith("http")) return val;
  return `${import.meta.env.BASE_URL}${val}`;
};

export const CUSTOM_BACK_SPRITE_URL = (clean: string): string | null => {
  const val = CUSTOM_BACK_SPRITES[clean];
  if (!val) return null;
  if (val.startsWith("http")) return val;
  return `${import.meta.env.BASE_URL}${val}`;
};

/** Strip default-form and mega/regional suffixes to get the bare Showdown base name (no hyphens). */
export function stripToShowdownBase(ps: string): string {
  return ps
    .replace(/megax$/, "").replace(/megay$/, "").replace(/megaz$/, "")
    .replace(/mega$/, "").replace(/gmax$/, "")
    .replace(/alola$/, "").replace(/galar$/, "")
    .replace(/hisui$/, "").replace(/paldea$/, "")
    .replace(/paldeacombat$/, "").replace(/paldeafire$/, "").replace(/paldeawater$/, "")
    .replace(/normal$/, "").replace(/altered$/, "").replace(/land$/, "")
    .replace(/ordinary$/, "").replace(/aria$/, "").replace(/incarnate$/, "")
    .replace(/male$/, "").replace(/female$/, "").replace(/shield$/, "")
    .replace(/average$/, "").replace(/standard$/, "").replace(/plant$/, "")
    .replace(/baile$/, "").replace(/midday$/, "").replace(/solo$/, "")
    .replace(/redmeteor$/, "").replace(/disguised$/, "").replace(/amped$/, "")
    .replace(/fullbelly$/, "").replace(/singlestrike$/, "").replace(/greenplumage$/, "")
    .replace(/familyoffour$/, "").replace(/zero$/, "").replace(/curly$/, "")
    .replace(/twosegment$/, "").replace(/redstriped$/, "").replace(/50$/, "")
    .replace(/ice$/, "");
}

/**
 * Build a prioritised fallback URL list for a sprite key.
 * Tries: local custom GIF → Showdown ani/ → gen5/ → dex/ → base-name extras.
 */
export function buildSpriteFallbacks(sprite: string, back = false): string[] {
  const clean = sprite.toLowerCase().replace(/[^a-z0-9-]/g, "");
  const ps = clean.replace(/-/g, "");
  const psBase = stripToShowdownBase(ps);
  const customUrl = CUSTOM_SPRITE_URL(clean);
  const customBackUrl = CUSTOM_BACK_SPRITE_URL(clean);
  const extras = psBase !== ps
    ? [`https://play.pokemonshowdown.com/sprites/ani/${psBase}.gif`,
       `https://play.pokemonshowdown.com/sprites/dex/${psBase}.png`]
    : [];
  if (back) {
    return [
      ...(customBackUrl ? [customBackUrl] : []),
      `https://play.pokemonshowdown.com/sprites/ani-back/${ps}.gif`,
      `https://play.pokemonshowdown.com/sprites/gen5-back/${ps}.png`,
      `https://play.pokemonshowdown.com/sprites/dex/${ps}.png`,
      ...(customUrl ? [customUrl] : []),
      ...extras,
    ];
  }
  return [
    ...(customUrl ? [customUrl] : []),
    `https://play.pokemonshowdown.com/sprites/ani/${ps}.gif`,
    `https://play.pokemonshowdown.com/sprites/gen5/${ps}.png`,
    `https://play.pokemonshowdown.com/sprites/dex/${ps}.png`,
    ...extras,
  ];
}
